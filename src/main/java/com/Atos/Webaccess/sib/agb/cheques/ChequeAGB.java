package com.Atos.Webaccess.sib.agb.cheques;



public class ChequeAGB {


	
	private String numeroCompte;
	private String cle;
	private String banque;
	private String agence;
	private String numeroCheque;
	private String etatCheque;
	private String montantCheque;
	
	
	public String getNumeroCheque() {
		return numeroCheque;
	}
	public void setNumeroCheque(String numeroCheque) {
		this.numeroCheque = numeroCheque;
	}
	public String getNumeroCompte() {
		return numeroCompte;
	}
	public void setNumeroCompte(String numeroCompte) {
		this.numeroCompte = numeroCompte;
	}
	public String getCle() {
		return cle;
	}
	public void setCle(String cle) {
		this.cle = cle;
	}
	public String getBanque() {
		return banque;
	}
	public void setBanque(String banque) {
		this.banque = banque;
	}
	public String getAgence() {
		return agence;
	}
	public void setAgence(String agence) {
		this.agence = agence;
	}
	public String getEtatCheque() {
		return etatCheque;
	}
	public void setEtatCheque(String etatCheque) {
		this.etatCheque = etatCheque;
	}
	public String getMontantCheque() {
		return montantCheque;
	}
	public void setMontantCheque(String montantCheque) {
		this.montantCheque = montantCheque;
	}
	
	
}
